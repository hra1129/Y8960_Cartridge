# -----------------------------------------------------------------------------
#  mksong.py
#   Converts the LilyPond scores of Bach "Brandenburg Concerto No.3" into the
#   song data (brand3.inc) for BRAND3.COM (OPM + OPL2 player).
#
#   Usage: python mksong.py            -> writes brand3.inc
# -----------------------------------------------------------------------------
import os
from lyparse import parse_rosegarden

HERE = os.path.dirname(os.path.abspath(__file__))
UNIT = 64				# ticks per whole note (16th = 4 ticks)

OPM_CLOCK = 3579545.0
OPL_FS = 3579545.0 / 72.0

# OPM RL bits (reg 20h): bit7 = R, bit6 = L
OPM_L, OPM_C, OPM_R = 0x40, 0xC0, 0x80
HW_COND = 0xFF			# conductor (tempo only, no sound)

# Parts of the score (Rosegarden order)
VN1, VN2, VN3, VA1, VA2, VA3, VC1, VC2, VC3, VIOLONE = range(10)

# (part, hw channel [0-7: OPM, 8-16: OPL2], patch, pan, transpose)
#   OPM patch : 0 = strings, 1 = contrabass
#   OPL2 patch: 0 = cello,   1 = harpsichord
#   OPL2 pan  : 1 = left, 128 = center, 255 = right
CHANNELS = [
	(VN1,     0, 0, OPM_L,   0),
	(VN2,     1, 0, OPM_C,   0),
	(VN3,     2, 0, OPM_R,   0),
	(VA1,     3, 0, OPM_L,   0),
	(VA2,     4, 0, OPM_C,   0),
	(VA3,     5, 0, OPM_R,   0),
	(VIOLONE, 6, 1, OPM_C, -12),		# violone 16'
	(VC1,     8, 0,  48,     0),
	(VC2,     9, 0, 128,     0),
	(VC3,    10, 0, 208,     0),
	(VIOLONE,11, 0, 128,     0),		# violone 8'
	(VIOLONE,12, 1, 160,     0),		# cembalo
]


# -----------------------------------------------------------------------------
def insert_rest(events, tick, length):
	"""Inserts a rest of 'length' ticks at 'tick' (splitting a note if needed)."""
	out = []
	t = 0
	done = False
	for n, d in events:
		if not done and t <= tick < t + d:
			if tick > t:
				out.append((n, tick - t))
				d -= tick - t
			out.append((None, length))
			done = True
		out.append((n, d))
		t += d
	if not done:
		out.append((None, length))
	return out


def merge_rests(events):
	out = []
	for n, d in events:
		if n is None and out and out[-1][0] is None:
			out[-1] = (None, out[-1][1] + d)
		else:
			out.append((n, d))
	return out


def build_song():
	"""Returns (parts, tempo_map). tempo_map = [(ticks, tempo60)], where
	tempo60 = 256 / (frames per tick) at 60Hz."""
	staves = parse_rosegarden(os.path.join(HERE, "Brandenburg_No3-BWV_1048.ly"), UNIT)
	parts = [ev for _, ev in staves]
	total = sum(d for _, d in parts[0])
	for p in parts:
		assert sum(d for _, d in p) == total

	# 1st movement (Allegro): 1/8 upbeat + 136 bars, 2nd movement (Adagio): 1 bar
	adagio = total - UNIT
	gap = 16
	parts = [insert_rest(p, adagio, gap) for p in parts]

	q = UNIT // 4
	tempo = [
		(adagio - 4 * q, 128),			# Allegro: 16th = 8 frames
		(q, 112), (q, 96), (q, 80), (q, 64),	# ritardando
		(gap, 64),				# pause between the movements
		(UNIT // 2, 64),			# Adagio
		(UNIT // 2, 40),			# fermata
	]
	assert sum(t for t, _ in tempo) == total + gap
	return parts, tempo


# -----------------------------------------------------------------------------
def enc_len(t):
	if 1 <= t <= 0x6F:
		return [0x7F + t]
	return [0xF0, t & 0xFF, t >> 8]


def encode_part(events, transpose):
	out = []
	cur = None
	for n, d in merge_rests(events):
		if d != cur:
			out += enc_len(d)
			cur = d
		if n is None:
			out.append(0)
		else:
			n += transpose
			assert 1 <= n <= 127
			out.append(n)
	out.append(0xFF)
	return out


def encode_conductor(tempo):
	out = []
	for ticks, t60 in tempo:
		t50 = min(255, (t60 * 6 + 2) // 5)
		out += [0xF8, t60, t50]
		out += enc_len(ticks)
		out.append(0)
	out.append(0xFF)
	return out


def opm_kc(n):
	n = max(13, min(n, 13 + 8 * 12 - 1))
	oct_ = (n - 13) // 12
	note = [0, 1, 2, 4, 5, 6, 8, 9, 10, 12, 13, 14][(n - 13) % 12]
	return (oct_ << 4) | note


def opl_fnum(n):
	f = 440.0 * 2.0 ** ((n - 69) / 12.0)
	for block in range(8):
		fnum = int(round(f * (1 << (20 - block)) / OPL_FS))
		if fnum < 1024:
			return fnum, block
	return 1023, 7


# -----------------------------------------------------------------------------
def db_lines(data, per=16):
	lines = []
	for i in range(0, len(data), per):
		lines.append("\t\t\tdb\t\t" + ", ".join("0x%02X" % b for b in data[i:i + per]))
	return lines


def main():
	parts, tempo = build_song()
	lines = [
		"; -----------------------------------------------------------------------------",
		"; brand3.inc  (generated by mksong.py, do not edit)",
		"; -----------------------------------------------------------------------------",
		"song_table:",
		"\t\t\tdb\t\t%d" % (len(CHANNELS) + 1),
		"\t\t\tdb\t\t0x%02X, 0, 0" % HW_COND,
		"\t\t\tdw\t\tstream_cond",
	]
	for i, (part, hw, patch, pan, tr) in enumerate(CHANNELS):
		lines.append("\t\t\tdb\t\t%d, %d, 0x%02X" % (hw, patch, pan))
		lines.append("\t\t\tdw\t\tstream_%d" % i)

	total = 0
	data = encode_conductor(tempo)
	total += len(data)
	lines.append("stream_cond:")
	lines += db_lines(data)
	for i, (part, hw, patch, pan, tr) in enumerate(CHANNELS):
		data = encode_part(parts[part], tr)
		total += len(data)
		lines.append("stream_%d:" % i)
		lines += db_lines(data)

	lines.append("opm_kc_table:")
	lines += db_lines([opm_kc(n) for n in range(128)])
	lines.append("opl_fnum_table:")
	tbl = []
	for n in range(128):
		fnum, block = opl_fnum(n)
		tbl += [fnum & 0xFF, (block << 2) | (fnum >> 8)]
	lines += db_lines(tbl)

	with open(os.path.join(HERE, "brand3.inc"), "w", newline="\r\n") as f:
		f.write("\n".join(lines) + "\n")
	frames = sum(t * 256 / t60 for t, t60 in tempo)
	print("stream bytes = %d, play time = %.1f sec (60Hz)" % (total, frames / 60.0))


if __name__ == "__main__":
	main()
