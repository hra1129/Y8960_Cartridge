# -----------------------------------------------------------------------------
#  mkmmiotest.py: generates mmiotest.inc for MMIOTEST.COM
#    pitch tables of the test arpeggio (C4 E4 G4 C5) for SSG / OPLL / OPL2 / OPM
#    and the ADPCM test sample (a chime tone, Y8950 ADPCM)
# -----------------------------------------------------------------------------
import math
import os

from mkcancan import (ADPCM_DELTA_N, ADPCM_FS, adpcm_encode, db_lines, opl_word,
	opll_word, opm_kc, ssg_word)

HERE = os.path.dirname(os.path.abspath(__file__))
NOTES = [60, 64, 67, 72]


def words(name, values):
	data = []
	for w in values:
		data += [w & 0xFF, w >> 8]
	return [name + ":"] + db_lines(data)


def chime():
	fs = ADPCM_FS
	n = int(fs * 1.0)
	sig = []
	for i in range(n):
		t = i / fs
		env = math.exp(-t / 0.3) * (1.0 - math.exp(-t / 0.004))
		s = (math.sin(2 * math.pi * 523.25 * t)
			+ 0.5 * math.sin(2 * math.pi * 1046.5 * t)
			+ 0.25 * math.sin(2 * math.pi * 1568.0 * t))
		sig.append(s * env)
	peak = max(abs(x) for x in sig)
	sig = [x / peak * 24000 for x in sig]
	sig += [0.0] * ((-len(sig)) % 8 + 8)		# 4-byte unit + silent tail
	return adpcm_encode(sig)


def main():
	adpcm = chime()
	lines = [
		"; -----------------------------------------------------------------------------",
		"; mmiotest.inc  (generated by mkmmiotest.py, do not edit)",
		"; -----------------------------------------------------------------------------",
	]
	lines += words("ssg_pitch", [ssg_word(n) for n in NOTES])
	lines += words("opll_pitch", [opll_word(n) for n in NOTES])
	lines += words("opl_pitch", [opl_word(n) for n in NOTES])
	lines += words("opm_pitch", [opm_kc(n) for n in NOTES])
	lines.append("ADPCM_DELTA_N\t:= 0x%04X" % ADPCM_DELTA_N)
	lines.append("ADPCM_SIZE\t:= %d" % len(adpcm))
	lines.append("ADPCM_STOP\t:= 0x%04X" % (len(adpcm) // 4 - 1))
	lines.append("ADPCM_FRAMES\t:= %d" % int(len(adpcm) * 2 / ADPCM_FS * 60 + 1))
	lines.append("adpcm_data:")
	lines += db_lines(adpcm)
	with open(os.path.join(HERE, "mmiotest.inc"), "w", newline="\r\n") as f:
		f.write("\n".join(lines) + "\n")
	print("adpcm bytes = %d" % len(adpcm))


if __name__ == "__main__":
	main()
